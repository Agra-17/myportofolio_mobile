import 'package:material_ui/material_ui.dart';
import 'package:myportofolio_mobile/widgets/left_drawer.dart';
import 'package:myportofolio_mobile/widgets/project_card.dart';

class MyHomePage extends StatelessWidget {
  MyHomePage({super.key});

  final String npm = "2506624833";
  final String nama = "Muh. Agra Putra Davyza Chaniago";
  final String kelas = "PBP-B";

  final List<ItemHomepage> items = [
    ItemHomepage(
      "Lihat Achievement",
      Icons.emoji_events,
      const Color.fromARGB(255, 79, 128, 104),
    ),
    ItemHomepage(
      "Tambah Achievement",
      Icons.add_circle,
      const Color.fromARGB(255, 201, 217, 111),
    ),
    ItemHomepage(
      "Tambah Pengalaman",
      Icons.work_outline,
      const Color.fromARGB(255, 79, 128, 104),
    ),
    ItemHomepage("Logout", Icons.logout, Color.fromARGB(255, 168, 63, 50)),
  ];

  @override
  Widget build(BuildContext context) {
    // Scaffold menyediakan struktur visual dasar halaman (AppBar, Body, SnackBar).
    return Scaffold(
      // AppBar menampilkan bar bagian atas halaman aplikasi.
      appBar: AppBar(
        title: const Text(
